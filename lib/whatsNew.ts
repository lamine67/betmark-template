const MONTHS = ["января", "февраля", "марта", "апреля", "мая", "июня", "июля", "августа", "сентября", "октября", "ноября", "декабря"];

export function formatReleaseDate(iso: string): string {
  const [y, m, d] = iso.split("-").map(Number);
  return `${d} ${MONTHS[m - 1]} ${y} г.`;
}

// Для сайта: на основном (не крипто) хосте пункты с crypto: true и целиком пустые релизы не показываются
export function releasesForHost(isCrypto: boolean): WhatsNewRelease[] {
  return RELEASES.map((r) => ({
    ...r,
    added: r.added.filter((i) => isCrypto || !i.crypto),
    improved: r.improved.filter((i) => isCrypto || !i.crypto),
  })).filter((r) => r.added.length + r.improved.length > 0);
}
